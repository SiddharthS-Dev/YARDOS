/**
 * Development simulator for the vehicle registry.
 *
 * This exists because the authorised VAHAN access route is unresolved
 * (docs/open-items.md OI-01) and development cannot wait for it. It is a
 * SIMULATOR, and it never pretends otherwise:
 *
 *   - `source` is 'MOCK' on every record, which is persisted and displayed.
 *   - `authoritative` is false, so the vehicle service records the enrichment
 *     as UNAVAILABLE rather than VAHAN_VERIFIED. A mock-sourced vehicle is
 *     never shown as registry-verified anywhere in the platform.
 *   - The configuration guard refuses to start production with this provider.
 *
 * Behaviour is DETERMINISTIC: output is derived from a hash of the plate, so
 * the same registration always yields the same owner, financier and model.
 * Tests can assert on it, and a demo behaves the same way twice.
 *
 * It also simulates the failure modes that matter, so the retry, circuit
 * breaker and manual-review paths are exercised in development rather than
 * discovered in production:
 *   ~4% of plates are "not found", and ~3% raise a transient error.
 *
 * All names and addresses are obviously fictional (requirement S45: never use
 * real people's personal information).
 */
@Injectable()
export class MockVehicleRegistryProvider extends VehicleRegistryProvider {
  readonly name = 'mock';
  readonly configured = true;
  readonly authoritative = false;

  constructor(@Inject(APP_CONFIG) private readonly config: AppConfig) {
    super();
  }

  async lookup(normalizedRegistrationNumber: string): Promise<RegistryLookupResult> {
    const started = Date.now();
    const seed = hashToInt(normalizedRegistrationNumber);

    // A realistic latency band, so timeout handling and the gate's
    // non-blocking design are genuinely exercised locally.
    await delay(120 + (seed % 380));

    const roll = seed % 100;

    if (roll < 3) {
      throw new RegistryProviderError(
        'UPSTREAM_UNAVAILABLE',
        'Simulated upstream failure from the registry simulator.',
        true,
        503,
      );
    }

    if (roll < 7) {
      return {
        outcome: 'NOT_FOUND',
        record: null,
        latencyMs: Date.now() - started,
        httpStatus: 404,
      };
    }

    return {
      outcome: 'FOUND',
      record: this.buildRecord(normalizedRegistrationNumber, seed),
      latencyMs: Date.now() - started,
      httpStatus: 200,
    };
  }

  private buildRecord(registrationNumber: string, seed: number): VehicleRegistryRecord {
    const vehicleClass = pick(VEHICLE_CLASSES, seed, 1);
    const modelEntry = pick(MODELS[vehicleClass] ?? MODELS.CAR!, seed, 2);
    const hypothecated = seed % 10 < 8;
    const financierName = hypothecated ? pick(FINANCIER_NAMES, seed, 3) : null;

    const registrationYear = 2015 + (seed % 10);

    return {
      registrationNumber,
      vehicleClass,
      vehicleType: modelEntry.bodyType,
      make: modelEntry.make,
      model: modelEntry.model,
      variant: pick(VARIANTS, seed, 4),
      color: pick(COLOURS, seed, 5),
      fuelType: pick(FUEL_TYPES, seed, 6),
      manufacturingYear: registrationYear,
      registeredOwnerName: buildOwnerName(seed),
      registeredOwnerAddress: buildOwnerAddress(seed),
      financierName,
      hypothecationStatus: hypothecated
        ? HypothecationStatus.HYPOTHECATED
        : HypothecationStatus.NOT_HYPOTHECATED,
      registrationDate: new Date(Date.UTC(registrationYear, seed % 12, (seed % 27) + 1)),
      fitnessValidUpto: new Date(Date.UTC(registrationYear + 15, seed % 12, (seed % 27) + 1)),
      insuranceValidUpto: new Date(Date.UTC(2026, seed % 12, (seed % 27) + 1)),
      chassisNumberLast4: String(1000 + (seed % 9000)),
      engineNumberLast4: String(1000 + ((seed * 7) % 9000)),
      source: 'MOCK',
      retrievedAt: new Date(),
      raw: {
        simulator: true,
        notice:
          'Generated by MockVehicleRegistryProvider. NOT authoritative registry data. ' +
          'The authorised VAHAN/aggregator route is open item OI-01.',
        seed,
        providerLatencyBudgetMs: this.config.registry.timeoutMs,
      },
    };
  }
}

