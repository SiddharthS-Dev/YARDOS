function buildOwnerName(seed: number): string {
  return `${pick(GIVEN_NAMES, seed, 7)} ${pick(FAMILY_NAMES, seed, 8)}`;
}

function buildOwnerAddress(seed: number): string {
  const doorNumber = (seed % 180) + 1;
  return `${doorNumber}, ${pick(STREETS, seed, 9)}, ${pick(CITIES, seed, 10)}, Tamil Nadu`;
}

/** Stable 31-bit integer from the plate, so output never varies run to run. */
function hashToInt(value: string): number {
  const digest = createHash('sha256').update(value).digest();
  return digest.readUInt32BE(0) % 2_147_483_647;
}

function pick<T>(items: readonly T[], seed: number, salt: number): T {
  return items[(seed * salt) % items.length] as T;
}

function delay(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}
